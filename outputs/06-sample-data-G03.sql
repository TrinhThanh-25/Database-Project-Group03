     other status is used as a decision outcome.
   - [upstream] "manager" in approval is the "facility manager" role; sample
     approval decisions are made by facility staff or facility manager
     accounts only, as a data-realism convention (not DDL-enforced in
     Phase 1).
   - [logical-stage] USER_ACCOUNT.email is treated as a candidate key,
     so every inserted email is distinct.
   - [ddl-stage] DEPARTMENT.head_user_account_id and
     USER_ACCOUNT.department_id form a circular FK. Resolved the same way
     as the DDL: DEPARTMENT rows are inserted first with
     head_user_account_id = NULL, USER_ACCOUNT rows are inserted next, then
     an UPDATE sets department heads for departments that have one.
   - [ddl-stage] No allowed-value CHECK exists for ACCOUNT_STATUS.status_name
     or MAINTENANCE_STATUS.status_name; the status values inserted below
     (Active/Inactive/Suspended and Reported/In progress/Completed,
     respectively) are sample-stage choices, not schema-enforced.

 Open Questions Carried Forward (from outputs/03-logical-design-G03.md
 Section 6 and outputs/05-db-definition-G03.sql OPEN QUESTION blocks; none
 are resolved by this data, only illustrated where relevant):
   - What is the account_status allowed-value set? Sample uses Active,
     Inactive, Suspended as representative values only.
   - What are the allowed maintenance status values and transitions?
     Sample uses Reported, In progress, Completed as representative values.
   - Which prior booking status/trigger/actor sets Cancelled or No-show?
     Sample includes one Cancelled booking (booking_request_id 6, previously
     Approved) and one No-show booking (booking_request_id 7, previously
     Approved) as plausible illustrations only; no transition rule is
     asserted or enforced.
   - What criteria determine whether a booking requires approval, and are
     any bookings exempt from the approval workflow? Sample always routes
     non-pending bookings through an APPROVAL_DECISION row; no exemption
     case is modeled because the criteria are unresolved.
   - Must every approved/rejected booking have exactly one APPROVAL_DECISION
     row? Sample gives each approved/rejected/cancelled/no-show booking
     exactly one decision row as a convention, not as an enforced rule.
   - Does opening a maintenance record automatically set SPACE.current_status
     to "Under maintenance"? Sample manually sets SPACE (space_id for
     CR-102) to "Under maintenance" and separately inserts a matching
     MAINTENANCE_RECORD row; no synchronization logic exists or is implied.
   - Should expected_number_of_participants be constrained to <=
     SPACE.capacity? Sample keeps all participant counts at or below the
     booked space's capacity as a realism convention, not an enforced rule.

 Trigger Compliance:
   - No triggers implemented in Phase 1; sample data only needs to satisfy
     PK/FK/UNIQUE/NOT NULL/CHECK.

 Sample Coverage / Traceability:
