   - All surrogate `INT IDENTITY(1,1)` primary keys are left unassigned and
     are generated by SQL Server in strict insertion order. Lookup tables
     (ROLE, ACCOUNT_STATUS, DEPARTMENT, SPACE_STATUS, BOOKING_STATUS,
     FACILITY) and USER_ACCOUNT/SPACE are referenced downstream by natural
     unique columns (role_name, status_name, department_name, user_id,
     unique_space_code, facility_name) via scalar subqueries, so those
     references do not depend on identity numbering.
   - BOOKING_REQUEST has no natural unique column other than its surrogate
     PK, so APPROVAL_DECISION and USAGE_SESSION rows below reference it by
     the sequential identity values produced by the single BOOKING_REQUEST
     INSERT block in this script: booking_request_id 1-9, assigned in the
     literal row order written below (row 1 -> id 1, row 2 -> id 2, ...).
   - This script is not idempotent; it is designed for a single run against
     a freshly created schema. No IDENTITY_INSERT is used.

 Assumptions Carried Forward:
   - [upstream] DEPARTMENT and lookup entities (ROLE, ACCOUNT_STATUS,
