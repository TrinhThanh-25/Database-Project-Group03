     computer laboratory (LAB-CS-201, LAB-CS-999), project laboratory
     (LAB-PJ-301), meeting room (MR-405, MR-201), auditorium (AUD-001),
     student workspace (SW-110).
   - Space statuses covered: Available/In use (most spaces), Under
     maintenance (unique_space_code CR-102), Temporarily closed
     (unique_space_code MR-201), Retired (unique_space_code LAB-CS-999).
   - Facilities covered: Projector, Whiteboard, Microphone, Computer,
     Livestreaming Equipment, Air Conditioner - all assigned to at least
     one SPACE via SPACE_FACILITY.
   - Booking statuses covered (BOOKING_REQUEST.booking_status_id), by
